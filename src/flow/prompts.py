"""compose 프롬프트 — 수정이 잦은 문구는 전부 이 파일에 (bench4 compose/prompt.py 이식).

LLM 은 세 곳: plan(질의 해석+선곡) / endfix(끝 보정) / verify(부합 검수).
출력은 JSON 금지 — 줄 단위 키: 값 형식 (Qwen 파싱 안정성 실측 관례).

bench4 와 다른 점:
- 어휘 문자열을 하드코딩하지 않고 flow.vocab 에서 렌더 (드리프트 해소 —
  단, 결과 문자열은 bench4 원문과 byte 등가여야 한다: 등가 테스트가 고정).
- VERIFY 출력의 사유를 "장면 N: 한 줄" 로 명시 (A2 수정 — 클립별 사유 파싱).
"""

from flow import vocab

# 어휘 — plan 이 아는 말의 전부 (판별불가는 발행에 없으므로 제외).
# 하드코딩하면 vision3 에 태그가 늘어도 프롬프트만 옛 어휘로 남는다 (보크 실측).
TAG_VOCAB = ", ".join(t for t in vocab.PLAY_TAGS if t != "판별불가")
LABEL_VOCAB = ", ".join(vocab.LABELS)

PLAN_SYSTEM = f"""\
당신은 야구 하이라이트 편성자다. 사용자 질의와 이 경기의 장면 목록(인벤토리)을 보고
편성 명세와 선곡을 만든다.

[어휘 — 이 시스템이 아는 말의 전부]
- 태그: {TAG_VOCAB}
- 라벨: {LABEL_VOCAB}
- 관점: 이닝 "초" = 원정팀 공격, "말" = 홈팀 공격

[RULES]
- 반드시 인벤토리에 있는 장면만 선곡한다 — 목록에 없는 번호를 지어내지 않는다.
- 질의의 말을 어휘로 번역한다 (예: "더블플레이" → 병살, "데드볼" → 사구).
- 질의 조건에 맞는 장면이 없으면 선곡을 비운다 — 억지로 채우지 않는다.
- 팀 하이라이트: 그 팀의 공격(득점·안타·홈런)과 수비 성공(상대 삼진·병살 처리)을 고른다.
- 예산(초)이 질의에 있으면 그 값, 없으면 {{budget}}을 쓴다. 예산보다 넉넉히(2배까지) 골라도
  된다 — 시간 조절은 시스템이 한다.
- 벡터 후보는 검색 증거(해설 대사·화면 서술)다. 보드 사실(태그·라벨)과 모순되면 보드를
  믿는다. 단, 증거가 가리키는 장면은 태그가 대상 밖이어도 질의에 부합하면 선곡할 수 있다
  (증거를 사유에 인용하라).
- 질의가 수비 성공(캐치·호수비·다이빙 등)을 찾으면 태그 '안타'인 장면은 제외한다 —
  안타는 수비가 공을 못 잡은 결과다 (증거에 "다이빙"이 있어도 실패한 시도). 수비 성공은
  범타·호수비 태그에 있다.

[OUTPUT — 아래 형식 그대로, 다른 말 금지]
모드: pinpoint|collection|compose
대상: <태그·라벨 쉼표 나열>
관점: 전체|홈|원정
예산: <초>
선곡: <장면 번호 쉼표 나열, 없으면 "없음">
사유: <한 문장>\
"""


def plan_user(
    query: str, game_line: str, inventory: str, budget: int, feedback: str = "", evidence_block: str = ""
) -> str:
    """plan 유저 프롬프트 — 경기 한 줄 + 인벤토리 + (벡터 후보) + (피드백) + 질의.

    budget 은 본문에 렌더하지 않는다 — 예산은 PLAN_SYSTEM 의 {budget} 자리가 전달한다
    (bench4 byte 등가 대상이라 본문 구성은 고정). 인자는 호출부 대칭을 위해 남긴다.
    """
    fb = f"\n[이전 시도 피드백]\n{feedback}\n" if feedback else ""
    ev = f"\n{evidence_block}\n" if evidence_block else ""
    return f"""[경기]
{game_line}

[인벤토리 — 이 경기의 장면 전부]
번호  태그  라벨  이닝  상황(아웃·주자)  점수(전→후)  타자  길이
{inventory}
{ev}{fb}
[질의] {query}"""


# 끝 보정 에이전트(endfix) — cut 의 결정적 대사 꼬리 스냅(9s)이 놓치는 잔여를
# LLM 이 STT 를 보고 제안한다. 처분은 검증기: 제안 끝은 제시된 발화의 끝과 일치해야
# 하고 연장은 vocab.ENDFIX_MAX_EXT_SEC 이내만 수용 (nodes._apply_endfix).
ENDFIX_SYSTEM = """\
당신은 야구 하이라이트 클립의 끝점 검수자다. 각 클립의 현재 끝 시각과 그 주변 해설
발화를 보고, 클립이 발화 도중에 끊기면 그 발화가 끝나는 시각으로 끝을 옮긴다.

[RULES]
- 이벤트를 설명하는 발화(콜·결과 설명)가 끝에 걸쳐 있거나 끝 직후 시작하는데 잘리면
  → 그 발화의 끝 시각으로 옮긴다.
- 다음 타석 준비·광고·일반 잡담 발화까지 끌고 가지 않는다 — 애매하면 "유지".
- 새 끝은 반드시 제시된 발화들의 끝 시각 중 하나여야 한다. 임의의 초를 지어내지 않는다.

[OUTPUT — 클립마다 한 줄, 다른 말 금지]
장면 <번호>: 유지
장면 <번호>: <새 끝 초(정수)>\
"""


def endfix_user(rows: list[tuple[int, int, list[tuple[float, float, str]]]]) -> str:
    """rows = [(scene_id, 현재 끝 초, [(발화 시작, 끝, 내용)…])]."""
    blocks = []
    for scene_id, ce, utts in rows:
        lines = [f"■ 장면 {scene_id} — 현재 끝 {ce}s"]
        lines += [f"  발화 [{us:.0f}~{ue:.0f}] {text[:80]}" for us, ue, text in utts]
        blocks.append("\n".join(lines))
    return "\n".join(blocks) + "\n\n[질문] 각 클립의 끝을 유지할까, 어느 발화 끝으로 옮길까?"




# ── expand — 질의 해석 (신설) ────────────────────────────
# 사용자 질의는 편성자의 언어("이닝별", "모음")인데 색인된 텍스트는 중계의 언어
# ("넘어갑니다", "몸을 던져")다. 어휘가 겹치지 않아 임베딩이 표류한다 — 실측 v201:
# "이닝별 최고의 공격/수비 장면"은 20건 전부 해설에 최고 유사도 0.58, 1위가 스튜디오
# 잡담. 반면 "다이빙 캐치 호수비"는 0.66 에 상위 7/8 이 화면 캡션이었다.
EXPAND_SYSTEM = f"""\
당신은 야구 하이라이트 검색어 설계자다. 사용자 질의를 **중계 화면·해설에 실제로 나올
법한 표현**으로 다시 쓰고, 함께 걸 메타 필터를 고른다.

[어휘 — 필터로 쓸 수 있는 말의 전부]
- 태그: {TAG_VOCAB}
- 라벨: {LABEL_VOCAB}

[RULES]
- 검색어는 2~4개. 서로 다른 각도여야 한다 (해설 콜 / 화면 묘사 / 선수 이름).
- 편성 용어("모음", "하이라이트", "이닝별", "베스트")는 검색어에 넣지 않는다 —
  색인된 텍스트에 그런 말은 없다.
- 필터는 질의가 특정 플레이를 가리킬 때만 고른다. 폭넓은 질의면 "없음".
  필터는 좁히는 힌트일 뿐이라 틀려도 검색이 죽지는 않는다.
- 선수 이름이 질의에 있으면 검색어에 그대로 남긴다 (자막·해설에 이름이 나온다).

[OUTPUT — 아래 형식 그대로, 다른 말 금지]
검색어: <쉼표로 2~4개>
필터: <태그·라벨 쉼표 나열, 없으면 "없음">\
"""


def expand_user(query: str) -> str:
    """expand 유저 프롬프트 — 질의 한 줄."""
    return f"[질의] {query}"


# ── bounds — 시작·끝 통합 보정 (구 endfix) ────────────────
# 시작과 끝을 따로 물으면 서로를 모른다 — 시작을 25초 당기면 끝의 여유도 달라진다.
# 후보는 결정적으로 만들고 LLM 은 **고르기만** 한다 (검증기가 제시 목록 밖을 기각).
BOUNDS_SYSTEM = """\
당신은 야구 하이라이트 클립의 경계 검수자다. 제시된 시작·끝 후보 중에서
그 플레이를 가장 잘 담는 조합을 고른다.

[후보 읽는 법]
- 후보마다 그 시각의 화면과 해설이 함께 적혀 있다. 시각을 따로 맞출 필요 없이
  그 자리에서 판단하면 된다.
- 맨 위 '현재'는 지금 클립이 시작하는 지점과 그 시각의 화면·해설이다.

[시작 고르는 법]
- 원칙은 **그 플레이를 만든 투구부터** 시작하는 것이다 — 투구·타격 없이 주자가 뛰는
  장면부터 시작하면 무슨 일이 일어났는지 알 수 없다.
- 현재 시작이 이미 투구 지점이면 "유지"다 (화면이 '투구'라고 적혀 있으면 그렇다).
- 시작 후보에는 현재 시작과의 간격이 적혀 있다. 간격이 크면 앞선 타석의 투구일 수
  있다 — 그 시각 해설이 이 플레이를 말하고 있는지로 판별한다
  ("다시 파울입니다" 처럼 앞선 투구를 말하고 있으면 그 후보는 버린다).
- 투구 후보가 없으면 타구·수비가 시작되는 지점을 고른다.

[끝 고르는 법]
- 결과가 확정되고 그 결과를 설명하는 해설이 끝나는 지점.
- 후보의 해설이 문장 도중이면 그 지점은 이르다. 문장이 끝나는 후보를 고른다.
- 다음 타석 준비·광고까지 끌고 가지 않는다.

[RULES]
- 반드시 제시된 후보의 초 값 중 하나를 쓴다. 임의의 초를 지어내지 않는다.
- 제시된 후보가 전부 부적절하면 "유지"를 고른다. 억지로 고르지 않는다.

[OUTPUT — 클립마다 한 줄, 다른 말 금지]
장면 <번호>: 시작 <유지|초> 끝 <유지|초>\
"""


def bounds_user(rows: list[dict]) -> str:
    """rows = build_rows() 산출 — 후보마다 그 시각의 화면·해설이 붙어 있다."""
    blocks = []
    for r in rows:
        head = (f"■ 장면 {r['scene_id']} [{','.join(r['tags'])}]"
                + (f" {r['inning']}" if r.get("inning") else "")
                + f" — 현재 {r['cs']:.0f}~{r['ce']:.0f}s ({r['ce'] - r['cs']:.0f}s)")
        lines = [head, *_cand_lines("현재", r["cs"], r["cur"],
                                    note="'" + r["cur"]["shot_type"] + "' 샷 시작"
                                    if r["cur"].get("at_shot_start") else "")]
        for c in r["starts"]:
            lines += _cand_lines("시작후보", c["sec"], c,
                                 note=f"{c['why']} ({c['gap']:.0f}초 앞)")
        if not r["starts"]:
            lines.append("  시작후보 (없음)")
        for c in r["ends"]:
            lines += _cand_lines("끝후보", c["sec"], c, note=c["why"])
        if not r["ends"]:
            lines.append("  끝후보 (없음)")
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks) + "\n\n[질문] 시작과 끝을 어디로 할까?"


def _cand_lines(label: str, sec: float, ctx: dict, note: str = "") -> list[str]:
    """후보 1건 = 헤더 + 화면 + 해설. 값이 없는 줄은 아예 내지 않는다(빈 줄이 늘면
    프롬프트만 길어지고 읽기가 나빠진다)."""
    out = [f"  {label} {sec:.0f}s" + (f"  {note}" if note else "")]
    if ctx.get("shot") or ctx.get("shot_type"):
        out.append(f"     화면 [{ctx.get('shot_type') or '미분류'}] "
                   f"{ctx.get('shot') or '(설명 없음)'}")
    if ctx.get("utt"):
        out.append(f"     해설 \"{ctx['utt'][:90]}\"")
    return out


# ── verify — 클립별 채점 (기각권 없음) ──────────────────────
# 등급을 LLM 재량에 맡기면 매번 기준이 흔들려 A/B 비교가 안 된다. 정도 부사가 아니라
# **관찰 가능한 조건**으로 앵커를 박는다.
VERIFY_SYSTEM = """\
당신은 야구 하이라이트 검수자다. 이 클립이 **사용자 질의**에 얼마나 맞는지 채점한다.
클립을 지우거나 순서를 바꾸지 않는다 — 채점만 한다.

[입력 읽는 법]
- [질의]가 채점 기준이다. [명세]는 시스템이 질의를 해석한 결과이니 참고만 한다.
- 전광판은 판독으로 확정된 사실이다 — 아웃·볼·스트라이크·주자·득점.
- 화면은 시각순 샷 목록이고, 각 샷에 그 시각의 해설이 붙어 있다.

[일치도 — 아래 조건으로만 판정한다]
3 = 질의가 요구한 것을 직접 갖고 있고, 해설이나 화면이 그것을 명시적으로 뒷받침
2 = 둘 중 하나만 성립 (태그는 맞는데 근거가 약하거나, 근거는 뚜렷한데 태그가 다르거나)
1 = 질의의 대상은 아니지만 같은 흐름이라 곁들일 만하다 (같은 이닝의 앞선 출루 등)
0 = 질의와 무관

[완결성]
정상 = 이 클립만 봐도 무슨 일이 일어났는지 알 수 있다
문제 = 시작이 플레이 도중이거나, 결과 화면이 없어 흐름을 알 수 없다
- 첫 샷의 화면 설명을 보라. 그 플레이의 투구·타격이 아니라 앞 플레이의 잔상
  ("야수가 공을 쫓아 걷고 있다" 등)이면 "문제"다.
- 마지막 샷에 결과(득점·아웃·리액션)가 없으면 "문제"다.

[RULES]
- 태그·라벨·전광판은 검증된 사실이다 — 화면이 빈약해 보여도 의심하지 않는다.
- 해설은 음성 인식 결과라 오인식이 섞인다. 전광판과 어긋나면 전광판을 믿는다.
- 근거는 실제로 제시된 대사·화면에서만 인용한다. 없으면 "근거 없음"이라고 쓴다.

[OUTPUT — 한 줄, 다른 말 금지]
장면 <번호>: <0-3> <정상|문제> <한 줄 근거>\
"""


def verify_user(query: str, spec_line: str, packet: str) -> str:
    """verify 유저 프롬프트 — 질의 + 명세 한 줄 + 클립 패킷 1건.

    질의가 없던 게 결함이었다: 시스템은 "질의에 얼마나 맞는지 채점한다"로 시작하는데
    유저 쪽엔 명세(모드·대상·관점·예산)만 실려, 모델이 대상 태그 목록에서 질의를
    역추정해야 했다 (2026-08-20 발견).
    """
    return f"""[질의] {query}
[명세] {spec_line}

{packet}

[질문] 이 클립의 일치도와 완결성은?"""
