"""compose 프롬프트 — 수정이 잦은 문구는 전부 이 파일에 (bench4 compose/prompt.py 이식).

LLM 은 세 곳: plan(질의 해석+선곡) / endfix(끝 보정) / verify(부합 검수).
출력은 JSON 금지 — 줄 단위 키: 값 형식 (Qwen 파싱 안정성 실측 관례).

bench4 와 다른 점:
- 어휘 문자열을 하드코딩하지 않고 flow.vocab 에서 렌더 (드리프트 해소 —
  단, 결과 문자열은 bench4 원문과 byte 등가여야 한다: 등가 테스트가 고정).
- VERIFY 출력의 사유를 "장면 N: 한 줄" 로 명시 (A2 수정 — 클립별 사유 파싱).
"""

from flow import vocab

# 어휘 — plan 이 아는 말의 전부 (판별불가는 발행에 없으므로 제외).
# 하드코딩하면 vision3 에 태그가 늘어도 프롬프트만 옛 어휘로 남는다 (보크 실측).
TAG_VOCAB = ", ".join(t for t in vocab.PLAY_TAGS if t != "판별불가")
LABEL_VOCAB = ", ".join(vocab.LABELS)

PLAN_SYSTEM = f"""\
당신은 야구 하이라이트 편성자다. 사용자 질의와 이 경기의 장면 목록(인벤토리)을 보고
편성 명세와 선곡을 만든다.

[어휘 — 이 시스템이 아는 말의 전부]
- 태그: {TAG_VOCAB}
- 라벨: {LABEL_VOCAB}
- 관점: 이닝 "초" = 원정팀 공격, "말" = 홈팀 공격

[RULES]
- 반드시 인벤토리에 있는 장면만 선곡한다 — 목록에 없는 번호를 지어내지 않는다.
- 질의의 말을 어휘로 번역한다 (예: "더블플레이" → 병살, "데드볼" → 사구).
- 질의 조건에 맞는 장면이 없으면 선곡을 비운다 — 억지로 채우지 않는다.
- 팀 하이라이트: 그 팀의 공격(득점·안타·홈런)과 수비 성공(상대 삼진·병살 처리)을 고른다.
- 예산(초)이 질의에 있으면 그 값, 없으면 {{budget}}을 쓴다. 예산보다 넉넉히(2배까지) 골라도
  된다 — 시간 조절은 시스템이 한다.
- 벡터 후보는 검색 증거(해설 대사·화면 서술)다. 보드 사실(태그·라벨)과 모순되면 보드를
  믿는다. 단, 증거가 가리키는 장면은 태그가 대상 밖이어도 질의에 부합하면 선곡할 수 있다
  (증거를 사유에 인용하라).
- 질의가 수비 성공(캐치·호수비·다이빙 등)을 찾으면 태그 '안타'인 장면은 제외한다 —
  안타는 수비가 공을 못 잡은 결과다 (증거에 "다이빙"이 있어도 실패한 시도). 수비 성공은
  범타·호수비 태그에 있다.

[OUTPUT — 아래 형식 그대로, 다른 말 금지]
모드: pinpoint|collection|compose
대상: <태그·라벨 쉼표 나열>
관점: 전체|홈|원정
예산: <초>
선곡: <장면 번호 쉼표 나열, 없으면 "없음">
사유: <한 문장>\
"""


def plan_user(
    query: str, game_line: str, inventory: str, budget: int, feedback: str = "", evidence_block: str = ""
) -> str:
    """plan 유저 프롬프트 — 경기 한 줄 + 인벤토리 + (벡터 후보) + (피드백) + 질의.

    budget 은 본문에 렌더하지 않는다 — 예산은 PLAN_SYSTEM 의 {budget} 자리가 전달한다
    (bench4 byte 등가 대상이라 본문 구성은 고정). 인자는 호출부 대칭을 위해 남긴다.
    """
    fb = f"\n[이전 시도 피드백]\n{feedback}\n" if feedback else ""
    ev = f"\n{evidence_block}\n" if evidence_block else ""
    return f"""[경기]
{game_line}

[인벤토리 — 이 경기의 장면 전부]
번호  태그  라벨  이닝  상황(아웃·주자)  점수(전→후)  길이
{inventory}
{ev}{fb}
[질의] {query}"""


# 끝 보정 에이전트(endfix) — cut 의 결정적 대사 꼬리 스냅(9s)이 놓치는 잔여를
# LLM 이 STT 를 보고 제안한다. 처분은 검증기: 제안 끝은 제시된 발화의 끝과 일치해야
# 하고 연장은 vocab.ENDFIX_MAX_EXT_SEC 이내만 수용 (nodes._apply_endfix).
ENDFIX_SYSTEM = """\
당신은 야구 하이라이트 클립의 끝점 검수자다. 각 클립의 현재 끝 시각과 그 주변 해설
발화를 보고, 클립이 발화 도중에 끊기면 그 발화가 끝나는 시각으로 끝을 옮긴다.

[RULES]
- 이벤트를 설명하는 발화(콜·결과 설명)가 끝에 걸쳐 있거나 끝 직후 시작하는데 잘리면
  → 그 발화의 끝 시각으로 옮긴다.
- 다음 타석 준비·광고·일반 잡담 발화까지 끌고 가지 않는다 — 애매하면 "유지".
- 새 끝은 반드시 제시된 발화들의 끝 시각 중 하나여야 한다. 임의의 초를 지어내지 않는다.

[OUTPUT — 클립마다 한 줄, 다른 말 금지]
장면 <번호>: 유지
장면 <번호>: <새 끝 초(정수)>\
"""


def endfix_user(rows: list[tuple[int, int, list[tuple[float, float, str]]]]) -> str:
    """rows = [(scene_id, 현재 끝 초, [(발화 시작, 끝, 내용)…])]."""
    blocks = []
    for scene_id, ce, utts in rows:
        lines = [f"■ 장면 {scene_id} — 현재 끝 {ce}s"]
        lines += [f"  발화 [{us:.0f}~{ue:.0f}] {text[:80]}" for us, ue, text in utts]
        blocks.append("\n".join(lines))
    return "\n".join(blocks) + "\n\n[질문] 각 클립의 끝을 유지할까, 어느 발화 끝으로 옮길까?"


VERIFY_SYSTEM = """\
당신은 야구 하이라이트 최종 검수자다. 이 클립들은 편성자가 이미 질의에 맞게 고른 것이다.
당신의 일은 재편성이 아니라 명백한 오배치 하나를 놓치지 않는 것뿐이다.

[기각해도 되는 경우 — 이 두 가지뿐]
1. 관점 위반: 명세 관점이 홈/원정인데 반대 팀의 플레이인 클립 ("초"=원정 공격, "말"=홈 공격)
2. 무관: 클립의 태그·라벨·대사 어느 것도 질의와 관련이 없는 클립

[기각하면 안 되는 경우]
- 태그(사실)는 전광판+해설로 이미 검증된 값이다 — 화면 유형 순서가 빈약해 보여도
  태그를 의심하지 않는다 (화면은 대표 프레임 요약일 뿐이다).
- 대상 목록은 편성 참고다 — 목록의 라벨 전부가 아니라 하나라도 걸치면 통과.
- 편성자가 서사를 위해 넣은 주변 플레이(번트·범타 등)도 통과.
- 애매하면 통과.

[OUTPUT — 아래 형식 그대로, 다른 말 금지]
판정: ok|부족
기각: <장면 번호 쉼표 나열, 없으면 "없음">
사유: 없음 | 기각마다 한 줄 — "장면 <번호>: <한 줄>"\
"""


def verify_user(spec_line: str, packets: str) -> str:
    """verify 유저 프롬프트 — 명세 한 줄 + 클립 패킷."""
    return f"""[편성 명세]
{spec_line}

[클립 목록]
{packets}

[질문] 명세에 맞지 않는 클립 번호는?"""
