from flow import vocab

# 어휘 — select_clips 가 아는 말의 전부 (판별불가는 발행에 없으므로 제외).
# 하드코딩하면 vision3 에 태그가 늘어도 프롬프트만 옛 어휘로 남는다 (보크 실측).
TAG_VOCAB = ", ".join(t for t in vocab.PLAY_TAGS if t != "판별불가")
LABEL_VOCAB = ", ".join(vocab.LABELS)

PLAN_SYSTEM = f"""\
당신은 야구 하이라이트 편성자다. 사용자 질의와 이 경기의 장면 목록(인벤토리)을 보고
편성 명세와 선곡을 만든다.

[어휘 — 이 시스템이 아는 말의 전부]
- 태그: {TAG_VOCAB}
- 라벨: {LABEL_VOCAB}
- 관점: 이닝 "초" = 원정팀 공격, "말" = 홈팀 공격

[RULES]
- 반드시 인벤토리에 있는 장면만 선곡한다 — 목록에 없는 번호를 지어내지 않는다.
- 질의의 말을 어휘로 번역한다 (예: "더블플레이" → 병살, "데드볼" → 사구).
- 질의 조건에 맞는 장면이 없으면 선곡을 비운다 — 억지로 채우지 않는다.
- 팀 하이라이트: 그 팀의 공격(득점·안타·홈런)과 수비 성공(상대 삼진·병살 처리)을 고른다.
- 예산(초)이 질의에 있으면 그 값, 없으면 {{budget}}을 쓴다. 예산보다 넉넉히(2배까지) 골라도
  된다 — 시간 조절은 시스템이 한다.
- 벡터 후보는 검색 증거(해설 대사·화면 서술)다. 보드 사실(태그·라벨)과 모순되면 보드를
  믿는다. 단, 증거가 가리키는 장면은 태그가 대상 밖이어도 질의에 부합하면 선곡할 수 있다
- 질의가 수비 성공(캐치·호수비·다이빙 등)을 찾으면 태그 '안타'인 장면은 제외한다 —
  안타는 수비가 공을 못 잡은 결과다 (증거에 "다이빙"이 있어도 실패한 시도). 수비 성공은
  범타·호수비 태그에 있다.

[OUTPUT — 아래 형식 그대로, 다른 말 금지]
모드: pinpoint|collection|compose
대상: <태그·라벨 쉼표 나열>
관점: 전체|홈|원정
예산: <초>
선곡: <장면 번호 쉼표 나열, 없으면 "없음">\
"""


def plan_user(
    query: str, game_line: str, inventory: str, budget: int, feedback: str = "", evidence_block: str = ""
) -> str:
    """plan 유저 프롬프트 — 경기 한 줄 + 인벤토리 + (벡터 후보) + (피드백) + 질의.

    budget 은 본문에 렌더하지 않는다 — 예산은 PLAN_SYSTEM 의 {budget} 자리가 전달한다
    (bench4 byte 등가 대상이라 본문 구성은 고정). 인자는 호출부 대칭을 위해 남긴다.
    """
    fb = f"\n[이전 시도 피드백]\n{feedback}\n" if feedback else ""
    ev = f"\n{evidence_block}\n" if evidence_block else ""
    return f"""[경기]
{game_line}

[인벤토리 — 이 경기의 장면 전부]
번호  태그  라벨  이닝  상황(아웃·주자)  점수(전→후)  타자  길이
{inventory}
{ev}{fb}
[질의] {query}"""


# ── expand — 질의 해석 (신설) ────────────────────────────
# 사용자 질의는 편성자의 언어("이닝별", "모음")인데 색인된 텍스트는 중계의 언어
# ("넘어갑니다", "몸을 던져")다. 어휘가 겹치지 않아 임베딩이 표류한다 — 실측 v201:
# "이닝별 최고의 공격/수비 장면"은 20건 전부 해설에 최고 유사도 0.58, 1위가 스튜디오
# 잡담. 반면 "다이빙 캐치 호수비"는 0.66 에 상위 7/8 이 화면 캡션이었다.
EXPAND_SYSTEM = f"""\
당신은 야구 하이라이트 검색어 설계자다. 사용자 질의를 **중계 화면·해설에 실제로 나올
법한 표현**으로 다시 쓰고, 함께 걸 메타 필터를 고른다.

[어휘 — 필터로 쓸 수 있는 말의 전부]
- 태그: {TAG_VOCAB}
- 라벨: {LABEL_VOCAB}

[RULES]
- 검색어는 2~4개. 서로 다른 각도여야 한다 (해설 콜 / 화면 묘사 / 선수 이름).
- 편성 용어("모음", "하이라이트", "이닝별", "베스트")는 검색어에 넣지 않는다 —
  색인된 텍스트에 그런 말은 없다.
- 필터는 질의가 특정 플레이를 가리킬 때만 고른다. 폭넓은 질의면 "없음".
  필터는 좁히는 힌트일 뿐이라 틀려도 검색이 죽지는 않는다.
- 선수 이름이 질의에 있으면 검색어에 그대로 남긴다 (자막·해설에 이름이 나온다).

[OUTPUT — 아래 형식 그대로, 다른 말 금지]
검색어: <쉼표로 2~4개>
필터: <태그·라벨 쉼표 나열, 없으면 "없음">\
"""


def expand_user(query: str) -> str:
    """expand 유저 프롬프트 — 질의 한 줄."""
    return f"[질의] {query}"


# ── bounds — 시작·끝 통합 보정 (구 endfix) ────────────────
# 시작과 끝을 따로 물으면 서로를 모른다 — 시작을 25초 당기면 끝의 여유도 달라진다.
# 후보는 결정적으로 만들고 LLM 은 **고르기만** 한다 (검증기가 제시 목록 밖을 기각).
BOUNDS_SYSTEM = """\
당신은 야구 하이라이트 클립의 경계 검수자다. 제시된 시작·끝 후보 중에서
그 플레이를 가장 잘 담는 조합을 고른다.

[후보 읽는 법]
- 후보마다 그 시각의 화면과 해설이 함께 적혀 있다. 시각을 따로 맞출 필요 없이 그 자리에서 판단하면 된다.
- 맨 위 '현재'는 지금 클립이 시작하는 지점과 그 시각의 화면·해설이다.

[시작 고르는 법]
- 원칙은 **그 플레이를 만든 투구부터** 시작하는 것이다. 투구·타격 없이 주자가 뛰는 장면부터 시작하면 무슨 일이 일어났는지 알 수 없다.
- 현재 시작이 이미 투구 지점이면 "유지"다 (화면이 '투구'라고 적혀 있으면 그렇다).
- 시작 후보는 **전부 현재 시작보다 뒤**이고, 얼마나 뒤인지가 적혀 있다("25초 뒤"). 시작을 앞으로 당기는 선택지는 없다. 고를 수 있는 건 "유지" 아니면 "미루기"다.
- **현재 시작이 이 플레이와 무관한 앞 타석이면 시작을 뒤로 미룬다.** 장면 경계가 앞 타석 꼬리를 무는 경우가 있다. 현재 시작의 해설이 다른 타자·다른 상황을 말하고 있고 뒤쪽에 이 플레이의 투구 후보가 있으면 그쪽을 고른다.
- 반대로 간격이 너무 크면 **다음** 타석의 투구일 수 있다. 그 시각 해설이 이 플레이를 말하고 있는지로 판별한다. 이미 결과를 말했거나 다른 타자를 부르면 버리고 "유지".
- 투구 후보가 없으면 타구·수비가 시작되는 지점을 고른다.

[끝 고르는 법]
- 결과가 확정되고 그 결과를 설명하는 해설이 끝나는 지점.
- 후보의 해설이 문장 도중이면 그 지점은 이르다. 문장이 끝나는 후보를 고른다.
- 다음 타석 준비·광고까지 끌고 가지 않는다.

[RULES]
- 반드시 제시된 후보의 초 값 중 하나를 쓴다. 임의의 초를 지어내지 않는다.
- 제시된 후보가 전부 부적절하면 "유지"를 고른다. 억지로 고르지 않는다.
- 해당 플레이만을 담을수 있는 시작과 끝을 고른다.

[OUTPUT — 클립마다 한 줄, 다른 말 금지]
장면 <번호>: 시작 <유지|초> 끝 <유지|초>\
"""


def bounds_user(rows: list[dict]) -> str:
    """rows = build_rows() 산출 — 후보마다 그 시각의 화면·해설이 붙어 있다."""
    blocks = []
    for r in rows:
        head = (f"■ 장면 {r['scene_id']} [{','.join(r['tags'])}]"
                + (f" {r['inning']}" if r.get("inning") else "")
                + f" — 현재 {r['cs']:.0f}~{r['ce']:.0f}s ({r['ce'] - r['cs']:.0f}s)")
        lines = [head, *_cand_lines("현재", r["cs"], r["cur"],
                                    note="'" + r["cur"]["shot_type"] + "' 샷 시작"
                                    if r["cur"].get("at_shot_start") else "")]
        for c in r["starts"]:
            lines += _cand_lines("시작후보", c["sec"], c,
                                 note=f"{c['why']} ({c['gap']:.0f}초 뒤)")
        if not r["starts"]:
            lines.append("  시작후보 (없음)")
        for c in r["ends"]:
            lines += _cand_lines("끝후보", c["sec"], c, note=c["why"])
        if not r["ends"]:
            lines.append("  끝후보 (없음)")
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks) + "\n\n[질문] 시작과 끝을 어디로 할까?"


def _cand_lines(label: str, sec: float, ctx: dict, note: str = "") -> list[str]:
    """후보 1건 = 헤더 + 화면 + 해설. 값이 없는 줄은 아예 내지 않는다(빈 줄이 늘면
    프롬프트만 길어지고 읽기가 나빠진다)."""
    out = [f"  {label} {sec:.0f}s" + (f"  {note}" if note else "")]
    if ctx.get("shot") or ctx.get("shot_type"):
        out.append(f"     화면 [{ctx.get('shot_type') or '미분류'}] "
                   f"{ctx.get('shot') or '(설명 없음)'}")
    if ctx.get("utt"):
        out.append(f"     해설 \"{ctx['utt'][:90]}\"")
    return out


